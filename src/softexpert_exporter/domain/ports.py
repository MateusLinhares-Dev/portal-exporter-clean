from __future__ import annotations
from datetime import datetime
from pathlib import Path
from typing import Any, Protocol
from softexpert_exporter.domain.models import ReportDescriptor, StoredFile, SyncJob, ExportMode

class FileStorage(Protocol):
    async def store(self, source: Path, relative_path: str, sha256: str, size_bytes: int) -> StoredFile: ...
    async def is_ready(self) -> bool: ...
    async def exists(self, relative_path: str) -> bool: ...

class JobRepository(Protocol):
    async def create_job(self, requested_by: str, mode: ExportMode, options: dict[str, Any]) -> SyncJob: ...
    async def get_job(self, job_id: str) -> SyncJob | None: ...
    async def claim_next_job(self) -> SyncJob | None: ...
    async def heartbeat(self, job_id: str) -> None: ...
    async def complete_job(self, job_id: str, *, total_records: int, downloaded: int, skipped: int, failed: int, error_summary: str | None) -> SyncJob: ...
    async def fail_job(self, job_id: str, error_summary: str) -> SyncJob: ...
    async def requeue_job(self, job_id: str, *, error_summary: str, next_attempt_at: datetime) -> SyncJob: ...
    async def recover_stale_jobs(self, stale_before: datetime) -> int: ...
    async def extracted_path(self, source_key: str) -> str | None: ...
    async def mark_extracted(self, *, job_id: str, source_key: str, descriptor: ReportDescriptor, destination_path: str, checksum_sha256: str, size_bytes: int) -> None: ...
    async def mark_extraction_failed(self, *, job_id: str, source_key: str, descriptor: ReportDescriptor, error_message: str) -> None: ...
    async def healthcheck(self) -> bool: ...
